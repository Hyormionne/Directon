REFUND_HEADER = "## 결제 수단별 환불 정리"
REFUND_TABLE = f"""{REFUND_HEADER}
브랜드 정보의 환불 안내를 결제 수단별로 정리한 것이다. 환불 기간과 절차가 서로 다르게 적혀 있으면 이 정리를 따른다.
- 환불은 결제한 수단 그대로 돌려드린다. 환불 기간은 그 주문의 결제수단(주문 조회 결과의 '결제수단') 줄만 말하고 다른 수단의 기간과 섞지 않는다. 결제수단을 모르면 "결제 수단에 따라 기간이 달라요"라고 하고, 필요하면 주문을 조회한다.
- 선불금(충전금)·네이버페이·카카오페이: 결제한 페이(충전금)로 환불된다. 환불 완료 후 바로, 늦어도 영업일 기준 1~2일 안에 들어간다. 계좌를 묻지 않는다.
- 신용·체크카드: 카드사 영업일 기준 3~4일 안에 승인 취소된다. 이미 청구됐으면 카드사에 문의해야 한다. 계좌를 묻지 않는다.
- 무통장입금·가상계좌: 환불받을 계좌(은행명, 계좌번호, 예금주)를 받아 영업일 기준 3~4일 안에 입금된다(화·목 일괄 지급). 계좌는 이 경우에만 받는다.
- 계좌이체: 결제한 계좌로 영업일 기준 2~3일 안에 환불된다. 계좌를 묻지 않는다.
- 휴대폰 결제: 결제한 달에 취소되면 휴대폰 요금에 청구되지 않는다. 달이 바뀌어 승인 취소가 안 되면 본인 명의 계좌를 받아 환불한다. 부분 취소는 안 된다.
- 반품 환불 순서: 회수한 상품이 물류센터에 입고된 뒤 환불이 접수된다(입고까지 최대 2주 정도). 그 뒤 결제 수단에 반영되기까지 2~3일 정도 더 걸릴 수 있다.
- 환불보장제도: 자사몰 구매 건은 수령 후 10일 안의 반품(효과 불만족 포함)을 운임 비용까지 완전 무상으로 접수한다. 이 경우 반품 배송비가 든다고 말하지 않는다."""


