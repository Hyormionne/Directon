def _read(s, zero="공"):
    return "".join(zero if c == "0" else D[c] for c in s)


def ph(num, zero="공", pause=None, sep=" "):
    """전화번호 읽기. pause=0.6이면 마디 사이에 쉼."""
    a, b, c = num[:3], num[3:7], num[7:]
    j = f" {{{pause}}} " if pause else sep
    return "{{" + num + "|" + j.join(_read(x, zero) for x in (a, b, c)) + "}}"


def od(oid, dash="다시", pause=None):
    """주문번호 읽기: 20261120-0041873 → 이공이육일일이공 다시 공공사일팔칠삼"""
    a, b = oid.split("-")
    j = f" {{{pause}}} {dash} " if pause else f" {dash} "
    return "{{" + oid + "|" + _read(a) + j + _read(b) + "}}"


